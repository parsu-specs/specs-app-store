export function darkPaletteFor(id: string) {
  return DARK_PALETTES[id as SitePaletteId] ?? DARK_PALETTES.candy;
}

export function palettesForMode(
  mode: "light" | "dark",
  lightPalettes: { id: string; label: string; swatches: string[] }[],
) {
  if (mode === "light") return lightPalettes;
  return SITE_PALETTE_IDS.map((id) => {
    const { label, colors } = DARK_PALETTES[id];
    return {
      id,
      label,
      swatches: [
        colors.background,
        colors.surface,
        colors.primary,
        colors.secondary,
        colors.accent,
      ],
    };
  });
}
